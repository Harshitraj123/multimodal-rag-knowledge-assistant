"""
Visual content retrieval.
Stores and retrieves visual assets (images, rendered pages, diagrams)
with their text descriptions for embedding-based search.
"""
from __future__ import annotations

import base64
import logging
import time
from typing import Any, Optional

logger = logging.getLogger(__name__)

VISUAL_COLLECTION = "rag_visuals"


class VisualRetriever:
    """
    Manages retrieval of visual assets.
    Visual content is indexed by its text description (generated by vision model).
    The original image bytes are stored in metadata for retrieval.
    """

    def __init__(self, persist_directory: str, embedder_model: str):
        self.persist_directory = persist_directory
        self.embedder_model = embedder_model
        self._client = None
        self._collection = None

    def _get_collection(self):
        if self._collection is None:
            import chromadb
            from chromadb.config import Settings
            if self._client is None:
                self._client = chromadb.PersistentClient(
                    path=self.persist_directory,
                    settings=Settings(anonymized_telemetry=False),
                )
            self._collection = self._client.get_or_create_collection(
                name=VISUAL_COLLECTION,
                metadata={"hnsw:space": "cosine"},
            )
        return self._collection

    def add_visual(
        self,
        visual_id: str,
        description: str,
        image_bytes: bytes,
        metadata: dict[str, Any],
    ) -> bool:
        """Index a visual asset with its description embedding."""
        from app.embeddings.embedder import embed_texts
        collection = self._get_collection()
        existing = collection.get(ids=[visual_id], include=[])
        if existing["ids"]:
            return False  # already indexed

        embs = embed_texts([description], model_name=self.embedder_model)
        # Store image as base64 in metadata (Chroma metadata is string-only)
        meta = {
            "doc_id": str(metadata.get("doc_id", "")),
            "source": str(metadata.get("source", "")),
            "page_number": int(metadata.get("page_number", 1)),
            "image_type": str(metadata.get("image_type", "unknown")),
            "image_b64": base64.b64encode(image_bytes).decode("ascii"),
        }
        collection.add(
            documents=[description],
            embeddings=embs,
            ids=[visual_id],
            metadatas=[meta],
        )
        return True

    def retrieve(
        self,
        query: str,
        top_k: int = 3,
    ) -> list[dict[str, Any]]:
        """Retrieve relevant visual assets by query similarity."""
        from app.embeddings.embedder import embed_query
        collection = self._get_collection()
        if collection.count() == 0:
            return []

        q_emb = embed_query(query, model_name=self.embedder_model)
        results = collection.query(
            query_embeddings=[q_emb],
            n_results=min(top_k, collection.count()),
            include=["documents", "metadatas", "distances"],
        )
        output = []
        for i, (doc, meta, dist) in enumerate(
            zip(results["documents"][0], results["metadatas"][0], results["distances"][0])
        ):
            img_b64 = meta.pop("image_b64", None)
            img_bytes = base64.b64decode(img_b64) if img_b64 else None
            output.append({
                "visual_id": results["ids"][0][i],
                "description": doc,
                "metadata": meta,
                "image_bytes": img_bytes,
                "score": max(0.0, 1.0 - dist),
                "retrieval_method": "visual_dense",
            })
        return output

    def count(self) -> int:
        return self._get_collection().count()
